import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = resolve(root, "js/data-products-browser.js");
const monitoringOutputPath = resolve(root, "js/monitoring-browser.js");

export async function browserBundle() {
  const result = await build({
    absWorkingDir: root,
    entryPoints: ["src/data-products/browser.js"],
    bundle: true,
    platform: "browser",
    format: "iife",
    target: "es2022",
    write: false,
    legalComments: "none",
    banner: {
      js: "// Generated by npm run build:browser. Edit src/data-products/ only.\n// Read-only: GET /v1/records only — never POST /v1/refresh.",
    },
    plugins: [
      {
        name: "browser-fixture-adapter",
        setup(build) {
          build.onResolve({ filter: /^\.\/node-fixture\.ts$/ }, () => ({
            path: resolve(root, "src/data-products/browser-fixture.ts"),
          }));
        },
      },
    ],
  });
  return result.outputFiles[0].text;
}

// Sentry error reporting (@sentry/browser), minified: it is inert unless the page has a
// sentry-dsn meta tag, so it stays a separate script from the data-products bundle.
export async function monitoringBundle() {
  const result = await build({
    absWorkingDir: root,
    entryPoints: ["src/monitoring/browser.ts"],
    bundle: true,
    platform: "browser",
    format: "iife",
    target: "es2022",
    minify: true,
    write: false,
    legalComments: "none",
    banner: {
      js: "// Generated by npm run build:browser from src/monitoring/. Errors only; off without a sentry-dsn meta tag.",
    },
  });
  return result.outputFiles[0].text;
}

async function readOrEmpty(path) {
  try {
    return await readFile(path, "utf8");
  } catch {
    return "";
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const outputs = [
    [outputPath, await browserBundle()],
    [monitoringOutputPath, await monitoringBundle()],
  ];
  if (process.argv.includes("--check")) {
    for (const [path, generated] of outputs) {
      if ((await readOrEmpty(path)) !== generated) {
        console.error(`${path} is stale; run npm run build:browser and commit the output.`);
        process.exitCode = 1;
      }
    }
  } else {
    for (const [path, generated] of outputs) await writeFile(path, generated);
  }
}
